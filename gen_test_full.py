def P(t="", center=False, soft=None, tab=False):
    p = doc.add_paragraph()
    r = p.add_run(t)
    if soft:
        r.add_break()
        p.add_run(soft)
    if tab:
        p.add_run("\t制表符后内容")
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p

def TBL(rows, cols, data):
    t = doc.add_table(rows=rows, cols=cols)
    for i in range(rows):
        for j in range(cols):
            t.cell(i, j).text = data[i][j]
    return t

def CNT():
    return sum(len(p.text) for p in doc.paragraphs)

